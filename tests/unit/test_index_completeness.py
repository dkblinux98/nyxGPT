"""Hand-maintained index docs must be reconciled against what they index (#4229).

An index that claims to cover a directory is a promise: a contributor who
reads it believes they have seen everything there is. When the index is
hand-maintained and nothing checks it, the promise decays silently and
monotonically -- every file added without an index line widens the gap, no
test goes red, and the missing document is reachable only by someone who
already knows its filename. `docs/README.md` had drifted exactly that way
(`unit-suite-expected-failures.md` was indexed nowhere), and
`security/README.md`'s suppression-file table had missed
`codeql-adjudications.yml` since #4222 added it.

This is the sibling defect to `tests/unit/test_context_index.py`'s, not the
same one: `agents/CONTEXT_INDEX.md` is *generated*, so its guard can diff the
committed file against the generator. A hand-maintained index has no such
oracle, so coverage has to be asserted as a property of the filesystem.

Two things are deliberate here:

* **One reconciliation, many indexes.** `_unnamed_entries` is the only place
  that decides what "indexed" means. A second index doc gets a row in
  `INDEXED_DIRECTORIES`, not a second copy of the logic.
* **The registry guards itself.** `test_every_index_like_document_is_classified`
  enumerates index-looking documents from the tree and fails on any that this
  module neither reconciles nor explicitly records as not claiming coverage.
  Without it, the registry becomes one more hand-maintained list of the kind
  this module exists to distrust.
"""

from __future__ import annotations

import os
import re
import sys
from dataclasses import dataclass
from pathlib import Path

import pytest

pytestmark = pytest.mark.unit

REPO_ROOT = Path(__file__).resolve().parents[2]


@dataclass(frozen=True)
class IndexedDirectory:
    """An index document and the directory contents it claims to name."""

    index: str
    """Repo-relative path of the index document."""

    directory: str
    """Repo-relative directory it claims to cover."""

    pattern: str
    """Glob applied inside `directory` (non-recursive; files only)."""

    omitted: frozenset[str]
    """Filenames deliberately left unnamed -- each needs a reason in the comment above."""

    claim: str
    """The sentence in the index that makes the coverage claim, for the failure message."""


#: The indexes reconciled here. `omitted` is the explicit opt-out: a file
#: listed there is unnamed *on purpose*, and the reason belongs next to it.
INDEXED_DIRECTORIES: tuple[IndexedDirectory, ...] = (
    IndexedDirectory(
        index="docs/README.md",
        directory="docs",
        pattern="*.md",
        # The index does not list itself; `README.md` in the root points at it
        # as "the complete, grouped list", which is the claim being enforced.
        omitted=frozenset({"README.md"}),
        claim="the complete, grouped list of the engineering documentation",
    ),
    IndexedDirectory(
        index="security/README.md",
        directory="security",
        pattern="*",
        # The table's own file. Every other file in `security/` is a scanner
        # suppression/adjudication store and belongs in the table.
        omitted=frozenset({"README.md"}),
        claim='"This directory holds the suppression/allowlist files each scanner\'s CI step reads"',
    ),
)

#: Indexes another guard already reconciles. Recorded so this module's
#: inventory is complete without duplicating that guard's assertions.
GUARDED_ELSEWHERE: dict[str, str] = {
    # Generated by `scripts/build_context_index.py`; its guard diffs the
    # committed file against the generator and asserts workflow/script coverage.
    "agents/CONTEXT_INDEX.md": "tests/unit/test_context_index.py",
}

#: Index-*looking* documents that claim no directory coverage, with why. A
#: document here is free to drift relative to its directory because it never
#: told anyone it was complete.
NOT_AN_INDEX: dict[str, str] = {
    "README.md": (
        "the root pointer layer (#3743) -- identity, a minimal install pointer, and a "
        "link to docs/README.md; it indexes no directory itself"
    ),
    "scripts/agents/README.md": (
        "a usage guide for the agent scripts grouped by role, not a directory listing -- "
        "agents/CONTEXT_INDEX.md is the index of scripts/agents/ and is guarded"
    ),
    ".github/workflows/README-notification-workflows.md": (
        "an architecture note for the notification workflow family, not an index of "
        ".github/workflows/ -- agents/CONTEXT_INDEX.md is that index"
    ),
    "tests/integration/README.md": "how to run the integration suite; it names no test files",
    "tests/fixtures/bounded_output/README.md": "explains one fixture directory's purpose",
    "tests/fixtures/pytest_conftest_guard/README.md": "explains one fixture directory's purpose",
    "web/README.md": "the create-next-app scaffold's getting-started text",
    "web/tests/README.md": "how the web test infrastructure works; it names no test files",
}


def _repo_relative(path: Path) -> str:
    return path.relative_to(REPO_ROOT).as_posix()


def _unnamed_entries(spec: IndexedDirectory) -> list[str]:
    """Filenames present in `spec.directory` that `spec.index` never names.

    The only definition of "indexed" in this module: the filename appears in
    the index text, not as the tail of a longer filename. Without that
    boundary, `cloud.md` would be satisfied by a line naming
    `cloud-artifact-smoke.md` -- which is how a completeness check becomes a
    completeness-shaped no-op.
    """
    text = (REPO_ROOT / spec.index).read_text(encoding="utf-8")
    directory = REPO_ROOT / spec.directory
    unnamed = []
    for path in sorted(directory.glob(spec.pattern)):
        if not path.is_file() or path.name in spec.omitted:
            continue
        if not re.search(rf"(?<![\w.-]){re.escape(path.name)}", text):
            unnamed.append(path.name)
    return unnamed


def _index_like_documents() -> list[str]:
    """Documents in the tree whose name advertises them as an index.

    `os.walk` with pruning rather than `rglob`, so `node_modules` and friends
    are never descended into. Symlinks are skipped: the packaged copy at
    `src/nyxgpt/resources/docs/README.md` is `docs/README.md`, and classifying
    one file twice would make the inventory lie about its own size.
    """
    skip = {
        ".git",
        ".mypy_cache",
        ".next",
        ".pytest_cache",
        ".ruff_cache",
        ".venv",
        "__pycache__",
        "build",
        "coverage",
        "dist",
        "htmlcov",
        "node_modules",
        "venv",
    }
    found = []
    for root, dirs, files in os.walk(REPO_ROOT):
        dirs[:] = sorted(d for d in dirs if d not in skip)
        for name in sorted(files):
            if not name.endswith(".md"):
                continue
            if not (name.startswith("README") or "INDEX" in Path(name).stem.upper()):
                continue
            path = Path(root) / name
            if path.is_symlink():
                continue
            found.append(_repo_relative(path))
    return found


@pytest.mark.parametrize("spec", INDEXED_DIRECTORIES, ids=lambda spec: spec.index)
def test_an_index_names_everything_in_the_directory_it_covers(spec: IndexedDirectory) -> None:
    """The gap is silent otherwise: nothing fails when a file is added unlisted."""
    unnamed = _unnamed_entries(spec)
    assert not unnamed, (
        f"{spec.index} claims to be {spec.claim}, but does not name "
        f"{sorted(unnamed)} from {spec.directory}/. Add an index line for each, "
        f"or add the filename to this spec's `omitted` set with the reason."
    )


@pytest.mark.parametrize("spec", INDEXED_DIRECTORIES, ids=lambda spec: spec.index)
def test_an_index_and_its_opt_outs_still_exist(spec: IndexedDirectory) -> None:
    """A stale opt-out is a hole that re-opens the moment the name is reused."""
    assert (REPO_ROOT / spec.index).is_file(), f"{spec.index} does not exist"
    directory = REPO_ROOT / spec.directory
    assert directory.is_dir(), f"{spec.directory} is not a directory"
    gone = sorted(name for name in spec.omitted if not (directory / name).exists())
    assert not gone, f"{spec.index}: `omitted` names files that no longer exist: {gone}"


def test_every_index_like_document_is_classified() -> None:
    """The registry above must cover the tree, or it is itself unguarded drift."""
    classified = (
        {spec.index for spec in INDEXED_DIRECTORIES} | set(GUARDED_ELSEWHERE) | set(NOT_AN_INDEX)
    )
    unclassified = sorted(set(_index_like_documents()) - classified)
    assert not unclassified, (
        f"index-looking documents this module does not classify: {unclassified}. "
        "Add each to INDEXED_DIRECTORIES (it claims to cover a directory), to "
        "GUARDED_ELSEWHERE (another test reconciles it), or to NOT_AN_INDEX with "
        "the reason it claims no coverage."
    )


def test_no_document_is_classified_two_ways() -> None:
    """Reconciled *and* excused is a contradiction that would read as covered."""
    reconciled = {spec.index for spec in INDEXED_DIRECTORIES}
    for label, other in (
        ("GUARDED_ELSEWHERE", set(GUARDED_ELSEWHERE)),
        ("NOT_AN_INDEX", set(NOT_AN_INDEX)),
    ):
        overlap = sorted(reconciled & other)
        assert not overlap, f"reconciled here and also listed in {label}: {overlap}"
    overlap = sorted(set(GUARDED_ELSEWHERE) & set(NOT_AN_INDEX))
    assert not overlap, f"listed in both GUARDED_ELSEWHERE and NOT_AN_INDEX: {overlap}"
    assert len(reconciled) == len(
        INDEXED_DIRECTORIES
    ), "duplicate index path in INDEXED_DIRECTORIES"


def test_classifications_name_files_that_exist() -> None:
    """A classification for a deleted file hides the next file that takes its path."""
    missing = sorted(
        path
        for path in (set(GUARDED_ELSEWHERE) | set(NOT_AN_INDEX))
        if not (REPO_ROOT / path).is_file()
    )
    assert not missing, f"classified documents that no longer exist: {missing}"
    absent_guards = sorted(
        guard for guard in GUARDED_ELSEWHERE.values() if not (REPO_ROOT / guard).is_file()
    )
    assert not absent_guards, f"GUARDED_ELSEWHERE points at missing guards: {absent_guards}"


def test_every_excuse_says_why() -> None:
    """ "Not an index" with no reason is an opt-out nobody can review."""
    thin = sorted(path for path, reason in NOT_AN_INDEX.items() if len(reason.strip()) < 20)
    assert not thin, f"NOT_AN_INDEX entries with no real reason: {thin}"


def test_a_longer_filename_does_not_satisfy_a_shorter_one(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The matcher's own regression test -- the way this guard would go quiet.

    A naive substring check reports `cloud.md` as indexed because the index
    happens to mention `cloud-artifact-smoke.md`. That still passes every
    assertion above while covering nothing, which is the exact failure mode
    #4229 exists to remove, so it is pinned rather than trusted.
    """
    monkeypatch.setattr(sys.modules[__name__], "REPO_ROOT", tmp_path)
    (tmp_path / "docs").mkdir()
    for name in ("cloud.md", "cloud-artifact-smoke.md", "ops.md", "README.md"):
        (tmp_path / "docs" / name).write_text("x", encoding="utf-8")
    (tmp_path / "docs" / "README.md").write_text(
        "- [Cloud smoke](cloud-artifact-smoke.md)\n- `extra-ops.md`\n", encoding="utf-8"
    )
    spec = IndexedDirectory(
        index="docs/README.md",
        directory="docs",
        pattern="*.md",
        omitted=frozenset({"README.md"}),
        claim="a fixture",
    )
    # `cloud.md` is only a tail of the listed name, and `ops.md` only a tail of
    # `extra-ops.md`: both must still read as unnamed.
    assert _unnamed_entries(spec) == ["cloud.md", "ops.md"]
