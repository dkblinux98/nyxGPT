"""The glitchtip-worker probe really reaches the Pod (#4208).

`tests/unit/test_glitchtip_worker_consumption.py` asserts that
`kustomization.yaml` generates `glitchtip-worker-probe` from
`glitchtip-worker-ready.py` and that the Deployment mounts a ConfigMap of that
name at the path the probe commands use. Those are three strings agreeing with
each other, and they can all three be right while the built overlay references
nothing: kustomize appends a content hash to a generated ConfigMap's name and
rewrites references to match, so the literal names in the sources are not the
names in the output.

The only way to know is to build it, which needs a real `kubectl` -- refused in
the unit suite by `tests/unit/conftest.py`'s host-stack guard, and correctly
so. It belongs here. `kustomize` reaches no cluster and changes nothing; the
marker is what keeps it out of the default unit run.

A dangling reference here is a Pod that cannot mount its probe volume, i.e.
every glitchtip-worker stuck in `ContainerCreating` -- the opposite failure
from the one #4208 fixed and just as total.
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

import pytest
import yaml

pytestmark = pytest.mark.integration

REPO_ROOT = Path(__file__).resolve().parents[2]
OBSERVABILITY_DIR = REPO_ROOT / "k8s" / "observability"


def test_kustomize_resolves_every_configmap_reference(tmp_path: Path) -> None:
    if shutil.which("kubectl") is None:
        pytest.skip("kubectl is not installed")

    # secret.yaml is generated by `nyxgpt ops` and gitignored, so a fresh
    # checkout has no buildable overlay. Stand the example in for it in a copy
    # rather than skipping -- a skip on a fresh checkout is a skip in CI.
    staged = tmp_path / "observability"
    shutil.copytree(OBSERVABILITY_DIR, staged)
    if not (staged / "secret.yaml").exists():
        shutil.copy(staged / "secret.example.yaml", staged / "secret.yaml")

    built = subprocess.run(
        ["kubectl", "kustomize", str(staged)],
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    docs = [doc for doc in yaml.safe_load_all(built) if doc]

    config_maps = {doc["metadata"]["name"] for doc in docs if doc.get("kind") == "ConfigMap"}
    referenced = {
        volume["configMap"]["name"]
        for doc in docs
        if doc.get("kind") in ("Deployment", "StatefulSet", "DaemonSet")
        for volume in doc["spec"]["template"]["spec"].get("volumes", [])
        if volume.get("configMap")
    }
    # Grafana's four provisioning ConfigMaps are deliberately absent from the
    # build: they are generated at apply time by
    # `ops._apply_k8s_grafana_provisioning` out of `docker/grafana/`, because
    # kustomize cannot read files above its own root (kustomization.yaml says
    # so). Naming them here rather than relaxing the assertion keeps the
    # difference deliberate -- the probe ConfigMap is in the overlay precisely
    # so that `kubectl apply -k` alone stands up a working worker, and a
    # regression that moved it to the ops-generated path would show up as this
    # list growing.
    OPS_GENERATED = {
        "grafana-alerting",
        "grafana-dashboard-providers",
        "grafana-dashboards",
        "grafana-datasources",
    }
    dangling = referenced - config_maps - OPS_GENERATED
    assert not dangling, (
        f"dangling ConfigMap reference(s) {sorted(dangling)} -- the Pods mounting them will "
        "never leave ContainerCreating"
    )

    probe_maps = [name for name in config_maps if name.startswith("glitchtip-worker-probe")]
    assert len(probe_maps) == 1, f"expected one generated probe ConfigMap, got {probe_maps}"

    # And it carries the probe's real contents under the key the probe
    # commands name, not an empty ConfigMap that mounts an empty directory.
    probe_map = next(doc for doc in docs if doc["metadata"]["name"] == probe_maps[0])
    probe_file = OBSERVABILITY_DIR / "glitchtip-worker-ready.py"
    assert probe_map["data"][probe_file.name] == probe_file.read_text()
