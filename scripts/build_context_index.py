#!/usr/bin/env python3
"""Generate agents/CONTEXT_INDEX.md -- the map agents read instead of the territory.

The bootstrap used to tell every agent to read `.github/workflows/*` and
`scripts/agents/*` in full: ~97k words, ~70% of the whole bootstrap corpus,
almost none of it relevant to any one run. This index states what each file
is in one line, so an agent knows what exists and opens only what it needs.

Regenerate with `python3 scripts/build_context_index.py`; the paired test
fails if the committed copy has drifted.

**It must cover every entry point in the directories it claims to index,
whatever the language (#4228).** This generator globbed `*.sh` only, so every
Python agent script and all of `scripts/agents/lib/` were off the map -- and
because the guard compared the committed file against this generator's own
output, the generator was its own oracle and certified the omission as
correct. `tests/unit/test_context_index.py` now enumerates those directories
straight from the filesystem, by a rule stated there rather than here, so a
narrower glob fails the build instead of quietly shrinking the map.
"""

from __future__ import annotations

import ast
import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
INDEX_PATH = REPO_ROOT / "agents" / "CONTEXT_INDEX.md"

HEADER = """# Agent context index

**Read this instead of reading every workflow and script.** One line per file:
what it is, and (for workflows) what starts it. Open a file only when the task
in hand needs its detail -- see `CLAUDE.md` section Bootstrap.

Every entry point in the indexed directories is listed, whatever its language.
`scripts/agents/lib/` is **listed too, not treated as internal**: 34 of its 37
modules carry a `__main__` and the workflows invoke them as commands, so an
omitted one is an invisible entry point exactly like an omitted top-level
script. Its table is separate only because those modules are reached *through*
a top-level script or workflow step, so that is where to start reading.

Generated by `scripts/build_context_index.py`; `tests/unit/test_context_index.py`
fails if it drifts or if it stops covering a directory it claims to index. Do
not hand-edit.
"""

SKIP_PREFIXES = ("#!", "set -", "IFS=", "export ", "shopt ")
COMMENT_NOISE = ("shellcheck", "vim:", "set -")
DOCSTRING_MARKS = ('"""', "'''")

#: Suffixes GitHub itself reads as a workflow definition.
WORKFLOW_SUFFIXES = (".yml", ".yaml")

#: Script languages this index can describe. Adding one here is half the job:
#: `_script_purpose` needs an arm that knows where that language states its
#: purpose, or the entry lands as `(no header comment)` and the paired test
#: fails -- which is the point.
SCRIPT_SUFFIXES = (".sh", ".py")


def _workflow_triggers(text: str) -> str:
    """Summarize a workflow's `on:` block without a YAML parse.

    Deliberately textual: these files carry multi-line `if:` expressions that a
    strict parse would choke on, and all we need here is the trigger names.
    """
    lines = text.splitlines()
    try:
        start = next(i for i, line in enumerate(lines) if re.match(r"^on:\s*$", line))
    except StopIteration:
        match = re.search(r"^on:\s*(.+)$", text, re.MULTILINE)
        return match.group(1).strip() if match else "?"

    triggers = []
    for line in lines[start + 1 :]:
        if line and not line.startswith((" ", "\t")):
            break
        found = re.match(r"^  ([a-z_]+):", line)
        if found:
            triggers.append(found.group(1))
    return ", ".join(triggers) or "?"


def _workflow_name(text: str, path: Path) -> str:
    match = re.search(r"^name:\s*(.+)$", text, re.MULTILINE)
    return match.group(1).strip().strip("\"'") if match else path.stem


def _strip_self_reference(body: str) -> str:
    """Drop a leading `path/name.sh --` prefix; the table already names the file."""
    stripped = re.sub(r"^(?:[\w./-]*/)?[\w.-]+\.(?:sh|py)\s*(?:[-—:]+\s*)?", "", body)
    return stripped.strip()


#: A line opening with one of these is a bullet, a synopsis or a box rule --
#: never the continuation of the sentence above it.
NON_PROSE_PREFIXES = ("[", "<", "-", "|", "*", "=")


def _is_prose(line: str) -> bool:
    """Reject argument synopses; a purpose line has to read like a sentence."""
    if line.startswith(NON_PROSE_PREFIXES):
        return False
    return len(line.split()) >= 4


def _opens_new_block(body: str) -> bool:
    """Whether `body` starts something other than more of the current sentence.

    One source for that judgement (D-066), shared by the header-comment arm and
    the `usage()` arm. Without it the comment arm swept a banner's `- bullets`
    and `=====` rule into `gh_project.sh`'s purpose line.
    """
    return not body or body.startswith(NON_PROSE_PREFIXES)


def _condense(block: str) -> str:
    """Join a wrapped prose block into one capped purpose line.

    The single source for "what a purpose line looks like" (D-066): the shell
    header-comment arm and the Python docstring arm must not drift apart on
    where a sentence ends or how long a line may get.
    """
    parts = []
    for line in block.splitlines():
        stripped = line.strip()
        if parts and _opens_new_block(stripped):
            break
        if not stripped:
            break
        parts.append(stripped)
        if stripped.endswith((".", ":")):
            break
    sentence = " ".join(parts)
    sentence = sentence.split(". ")[0].rstrip(".:")
    return sentence[:130].strip()


def _first_sentence(lines: list[str], index: int) -> str:
    """Join a wrapped comment block into one sentence, so it does not truncate."""
    parts = []
    for line in lines[index:]:
        stripped = line.strip()
        if not stripped.startswith("#"):
            break
        body = stripped.lstrip("#").strip()
        if not body:
            break
        parts.append(body)
        if body.endswith((".", ":")):
            break
    return _condense("\n".join(parts))


def _argparse_description(module: ast.Module) -> str:
    """The `description=` a script hands its argument parser, if it is a literal."""
    for node in ast.walk(module):
        if not isinstance(node, ast.Call):
            continue
        for keyword in node.keywords:
            if keyword.arg != "description":
                continue
            if isinstance(keyword.value, ast.Constant) and isinstance(keyword.value.value, str):
                return keyword.value.value
    return ""


def _python_purpose(text: str) -> str:
    """Where a Python script states its purpose: PEP 257 docstring, then argparse.

    Not in a `#` header and not in a `usage()` heredoc, which is why the shell
    arm could not see one at all -- the blind spot that kept every Python agent
    script off the map (#4228). Returns "" so the caller can fall through to
    the shell arm for a script that happens to carry a `#` header instead.
    """
    try:
        module = ast.parse(text)
    except SyntaxError:
        return ""
    for block in (ast.get_docstring(module) or "", _argparse_description(module)):
        purpose = _strip_self_reference(_condense(block))
        if purpose:
            return purpose
    return ""


def _script_purpose(text: str, path: Path) -> str:
    """One-line description of a script, in whatever language it is written.

    Two arms, one entry point. Python states its purpose in the module
    docstring or the `argparse` description, so that is read first for a
    `.py` file. Shell header comments in this tree sit in three places: above
    the shebang body, below `set -euo pipefail`, or -- for scripts that
    document themselves to the operator instead -- only inside a `usage()`
    heredoc. All of them are read, because a script with no line here is a
    script an agent has to open.
    """
    if path.suffix == ".py":
        purpose = _python_purpose(text)
        if purpose:
            return purpose

    lines = text.splitlines()
    for index, line in enumerate(lines):
        stripped = line.strip()
        if not stripped or stripped.startswith(SKIP_PREFIXES):
            continue
        if stripped.startswith("#"):
            body = stripped.lstrip("#").strip()
            if not body or set(body) <= {"-", "=", "#"}:
                continue
            if body.startswith(COMMENT_NOISE):
                continue
            cleaned = _strip_self_reference(_first_sentence(lines, index))
            if cleaned:
                return cleaned
            continue
        if stripped.startswith(DOCSTRING_MARKS):
            body = _strip_self_reference(stripped.strip("\"'").strip()).rstrip(".")
            if body:
                return body
            continue
        break

    usage = re.search(r"usage\(\)\s*\{\s*\n\s*cat <<-?'?\w+'?\s*\n(.*?)\nEOF", text, re.S)
    if usage:
        for candidate in usage.group(1).splitlines():
            candidate = _strip_self_reference(candidate.strip()).rstrip(".")
            if candidate and not candidate.lower().startswith("usage:") and _is_prose(candidate):
                return candidate
    return "(no header comment)"


def _files_with_suffixes(directory: Path, suffixes: tuple[str, ...]) -> list[Path]:
    """Entry points of the given languages directly inside `directory`.

    One discovery helper rather than a glob per table, so widening the index to
    another language is a change to `SCRIPT_SUFFIXES` and not to three call
    sites that can disagree (D-066).
    """
    return sorted(
        path for path in directory.iterdir() if path.is_file() and path.suffix in suffixes
    )


def _script_table(directory: Path, heading: str, column: str) -> list[str]:
    """One table per indexed script directory, rendered the same way each time."""
    out = [f"\n## {heading}\n", f"| {column} | Purpose |", "|---|---|"]
    for path in _files_with_suffixes(directory, SCRIPT_SUFFIXES):
        # A pipe in a purpose line would split the markdown row in two.
        purpose = _script_purpose(path.read_text(encoding="utf-8"), path).replace("|", "\\|")
        out.append(f"| `{path.name}` | {purpose} |")
    return out


def build() -> str:
    out = [HEADER, "\n## Workflows (`.github/workflows/`)\n"]
    out.append("| Workflow | Triggered by | Name |")
    out.append("|---|---|---|")
    for path in _files_with_suffixes(REPO_ROOT / ".github" / "workflows", WORKFLOW_SUFFIXES):
        text = path.read_text(encoding="utf-8")
        out.append(f"| `{path.name}` | {_workflow_triggers(text)} | {_workflow_name(text, path)} |")

    agents_dir = REPO_ROOT / "scripts" / "agents"
    out += _script_table(agents_dir, "Agent scripts (`scripts/agents/`)", "Script")
    out += _script_table(
        agents_dir / "lib",
        "Agent script libraries (`scripts/agents/lib/`)",
        "Module",
    )

    return "\n".join(out) + "\n"


if __name__ == "__main__":
    INDEX_PATH.write_text(build(), encoding="utf-8")
    print(f"wrote {INDEX_PATH.relative_to(REPO_ROOT)}")
